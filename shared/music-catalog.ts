function kevin(title: string, version: "3.0" | "4.0"): MusicLicence {
  const kind = LICENCES[version === "4.0" ? "cc-by-4.0" : "cc-by-3.0"];
  return {
    id: kind.id,
    name: `CC BY ${version}`,
    version,
    url: kind.url,
    attribution: `"${title}" Kevin MacLeod (incompetech.com)\nLicensed under Creative Commons: By Attribution ${version}\n${kind.url}`,
    attributionRequired: true,
  };
}

function cc0(attribution: string): MusicLicence {
  return { id: "cc0-1.0", name: "CC0 1.0", version: "1.0", url: LICENCES["cc0-1.0"].url, attribution, attributionRequired: false };
}

const upload = (path: string) => `https://upload.wikimedia.org/wikipedia/commons/${path}`;
const transcode = (path: string) => {
  const name = path.split("/").pop()!;
  return `https://upload.wikimedia.org/wikipedia/commons/transcoded/${path}/${name}.mp3`;
};
const filePage = (name: string) => `https://commons.wikimedia.org/wiki/File:${name}`;

