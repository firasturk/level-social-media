/**
 * The studio's starter music catalog: recordings whose licence allows commercial use in a client's
 * video AND keeping a copy in the studio for the team (docs/music-library.md has the research, the
 * sources excluded and why). Every entry records where it comes from, the licence and its version,
 * the credit line, and what the source says about Content ID. Verified on 23 October 2026 against
 * the Wikimedia Commons API (licence, author, SHA-1 and size of each file) and, for Kevin MacLeod,
 * incompetech.com (BPM, Content ID).
 *
 * No audio is in the repository: the server copies a track from `file.url` into our storage the
 * first time someone plays or uses it, checks the size and SHA-1 where they are pinned, and records
 * the copy (server/music.ts). Test audio is synthesised by the server from `synth` (CC0, ours).
 *
 * BPM: "source" is the composer's own figure (incompetech.com's catalogue); our beat analysis
 * (tempoFromEnvelope in shared/music.ts) agreed within 2 BPM on six of the nine Kevin MacLeod
 * tracks. Classical recordings without a steady pulse carry no BPM rather than a wrong one.
 */
import type { MusicContentId, MusicLicence, MusicMood, MusicSourceInfo } from "./music";
import { LICENCES } from "./music";
import { SCALES, type TestAudioSpec } from "./music-test-audio";

export interface CatalogFile {
  /** The canonical file we copy from (a Wikimedia Commons original, or Commons' own MP3 transcode of an Ogg original). */
  url: string;
  mime: "audio/mpeg" | "audio/wav";
  /** Pinned when the file is the Commons original: the copy must match. */
  bytes?: number;
  sha1?: string;
  /** How the file relates to the licensed original (e.g. "MP3 transcode of the Ogg original by Wikimedia Commons"). */
  note?: string;
}

export interface CatalogEntry {
  slug: string;
  title: string;
  artist: string;
  moods: MusicMood[];
  genre: string;
  /** Seconds. */
  duration: number;
  bpm: number | null;
  bpmSource: "source" | "measured" | null;
  file: CatalogFile | null;
  synth?: TestAudioSpec;
  source: MusicSourceInfo & {
    /** The original file's page when `page` is a different one. */
    filePage?: string;
    isrc?: string;
    /** Where the source says the recording came from. */
    origin?: string;
    /** The day the licence was read at the source. */
    verified: string;
  };
  licence: MusicLicence;
  contentId: MusicContentId;
  /** The licence lets us keep a copy and offer it to the team inside the studio. Copies are refused without it. */
  redistribution: boolean;
  test: boolean;
}

